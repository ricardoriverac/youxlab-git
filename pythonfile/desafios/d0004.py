n = input('Digite algo:')
print('\033[0;33;37m O tipo primitivo desse valor é \033[0;33;37m', type(n))
print('\033[0;33;37m Só tem espasços?\033[0;33;37m', n.isspace())
print('\033[0;33;37m É um número?\033[0;33;37m', n.isnumeric())
print('\033[0;33;37m É alfabetico?\033[0;33;37m', n.isalpha())
print('\033[0;33;37m É alfanumerico?\033[0;33;37m', n.isalnum())       
print('\033[0;33;37m Está em maiúsculas?\033[0;33;37m', n.isupper())
print('\033[0;33;37m Está em minusculas?\033[0;33;37m', n.islower())
print('\033[0;33;37m Está capitalizada?\033[0;33;37m', n.istitle())