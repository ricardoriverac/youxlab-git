n = input('\033[1;30;37mDigite algo:\033[1;30;37m')
print('\033[31m tipo primitivo desse valor é \033[31m', type(n))
print('\033[31mSó tem espasços?\033[31m', n.isspace())
print('\033[31mÉ um número?\033[31m', n.isnumeric())
print('\033[31mÉ alfabetico?\033[31m', n.isalpha())
print('\033[31mÉ alfanumerico?\033[31m', n.isalnum())       
print('\033[31mEstá em maiúsculas?\033[31m', n.isupper())
print('\033[31mEstá em minusculas?\033[31m', n.islower())
print('\033[31mEstá capitalizada?\033[31m', n.istitle())