# Minusculo é utilizado
frase = 'Curso em Vídeo Python'
print(frase.lower())

# Ver o tamanho da frase 
frase = 'Curso em Vídeo Python'
print(len(frase))

# Remover espaços 
frase = 'Curso em Vídeo Python'
