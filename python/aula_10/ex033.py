numero1 = int(input('Qual é o primeiro numero? '))
numero2 = int(input('Qual é o segundo numero? '))
numero3 = int(input('Qual é o terceiro numero? '))
numeros = [numero1, numero2, numero3]
print('O maior valor digitado foi {}'.format(max(numeros)))
print('O menor numero digitado foi {}'.format(min(numeros)))