'''Faça um programa que laia um número de 0 a ৭৭৭৭ ৫ mostra na tala cada um dos dígitos separados.
Ex:
Digite um número: 1834
unidade: 4 dezena: 3 centana: 8 milhar: 1'''

#Resposta

Digite_o_numero = input('Digite um número de 0 a ৭৭৭৭: ')

