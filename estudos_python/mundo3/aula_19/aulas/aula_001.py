#Comandos
#Contexto
Dicionario = { 'Nome':'Juam' , 'Idade':16 , 'Sexo':'Masculino'}

#Como mostrar somente os valores dentro de um dicionário
'''
Para isso, deve usar o comando ".values()" Ele mostra todos os valores 
no terminal
(OBS: ela a um comando interno, só funciona se tiver um printe ou alguma coisa antes)
'''
#Exemplo
print(Dicionario.values())

#Como mostrar somente as chaves
'''
Para isso, deve usar o comando ".keys()" Ele mostra todos as chaves
no terminal
(OBS: ela a um comando interno, só funciona se tiver um printe ou alguma coisa antes)
'''
#Exemplo
print(Dicionario.keys())

#Como fazer para aparecer tanto as chaves quanto os valores

'''
Utilizando o comando ".items()"
'''
#Exemplo
print(Dicionario.items())

