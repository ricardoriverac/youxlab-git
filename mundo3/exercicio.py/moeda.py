def metade(a):
    meta = a / 2
    print (f'A metade de {a} é {meta}')

def dobro(a):
    dobo = a * 2
    print (f'O dobro de {a} é {dobo}')

def aumento(a):
    aument = a*15/100
    aumen = a + aument
    print (f'{a} com 15% de aumento é {aumen}')

def redução(a=0):
    reduz = a*15/100
    reduzi = a - reduz
    print (f'{a} com 15% de redução é {reduzi}')